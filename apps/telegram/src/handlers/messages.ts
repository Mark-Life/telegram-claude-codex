const MAX_TRANSCRIPT_DISPLAY = 3800;

const REMINDERS_SKILL_RELATIVE = ".agents/skills/reminders/SKILL.md";

/** The free fast path: the word itself. Jev is asked only when this misses. */
const REMINDER_RE = /(?:напомин|remind|reminder)/iu;

/** Shorter than this, or a mistyped command, cannot be a reminder request. */
const MIN_JUDGED_CHARS = 3;

/**
 * The user's own reminders workflow, when they wrote one. It belongs to their
 * working directory, not to this repo, so it is named only when really there.
 */
const remindersSkillPath = () => {
  const base = workDir();
  const file =
    base === undefined ? undefined : path.join(base, REMINDERS_SKILL_RELATIVE);
  return file !== undefined && existsSync(file) ? file : undefined;
};

const describeReminderContext = (reminder: ReminderEntry) =>
  `#${reminder.id}: ${reminder.text}; due=${reminder.dueAt === undefined ? "none" : new Date(reminder.dueAt).toISOString()}; timezone=${reminder.timezone}`;

/**
 * The last visible /reminders page as the agent should read it: one line per
 * ordinal, so "the second one" resolves to a stable id.
 */
const describeReminderPage = async (ids: readonly number[] = []) => {
  const lines = await Promise.all(
    ids.map(async (id, index) => {
      const reminder = await getReminder(id);
      return reminder
        ? `${index + 1} -> ${describeReminderContext(reminder)}`
        : `${index + 1} -> #${id} (already completed)`;
    })
  );
  return lines.join("\n");
};

/**
 * The keyword scan missed; ask Jev, unless the surface or the text rules it
 * out. A group run is read-only and cannot reach the reminders CLI at all.
 */
const judgeReminderIntentFor = async (ctx: BotContext, userText: string) => {
  const trimmed = userText.trim();
  if (
    accessOf(ctx).surface === "group" ||
    trimmed.length < MIN_JUDGED_CHARS ||
    trimmed.startsWith("/")
  ) {
    return false;
  }
  return await asksForReminder({
    text: trimmed,
    userId: ctx.from?.id ?? 0,
  });
};

/** Context generated by bot UI is not in the agent session, so inject it. */
const reminderContextFor = async (ctx: BotContext, userText: string) => {
  if (!canManageTasks(accessOf(ctx).tier)) {
    return "";
  }
  const state = await getState(ctx);
  let linked: ReminderEntry | undefined;
  if (state.threadId === null) {
    const repliedTo = ctx.message?.reply_to_message?.message_id;
    if (repliedTo !== undefined) {
      linked = await getReminderByMessage({
        chatId: state.chatId,
        messageId: repliedTo,
      });
    }
  } else {
    linked = await getReminderByThread({
      chatId: state.chatId,
      threadId: state.threadId,
    });
  }
  const page = await describeReminderPage(state.lastReminderPage?.ids);
  const hasPage = page.length > 0;
  const skillFile = remindersSkillPath();
  const fastMatch = REMINDER_RE.test(userText);
  // Worth an inline call only where the verdict still changes the prompt: it
  // gates the skill line, and it is the one reason to inject the block at all.
  const undecided =
    !fastMatch &&
    (skillFile !== undefined || (linked === undefined && !hasPage));
  const reminderIntent =
    fastMatch || (undecided && (await judgeReminderIntentFor(ctx, userText)));
  if (linked === undefined && !hasPage && !reminderIntent) {
    return "";
  }
  const lines = ["[Private reminder context]"];
  if (reminderIntent && skillFile !== undefined) {
    lines.push(`Before acting, read ${skillFile} and follow it.`);
  }
  if (linked !== undefined) {
    lines.push(
      `This conversation is linked to ${describeReminderContext(linked)}.`
    );
  }
  if (hasPage) {
    lines.push(
      `The last visible /reminders page had this stable order:\n${page}`
    );
  }
  lines.push(
    "Use stable ids and this CLI for any requested reminder operation:",
    `bun ${REMINDERS_CLI} <list|show|add|update|done> [args]`
  );
  return lines.join("\n");
};

/**
 * Promise-facing bridge to the Effect TranscribeService: resolves the spoken
 * text or rejects (TranscriptionError) so the voice handlers keep a try/catch
 * shape.
 */
export const transcribeAudio = async (buffer: Buffer, filename: string) =>
  await runtime.runPromise(
    Effect.flatMap(TranscribeService, (service) =>
      service.transcribe(buffer, filename)
    )
  );

/**
 * Whether a voice note's transcript is shown back in the chat. A failed read
 * keeps the echo, which was the behaviour before the switch existed.
 */
const echoTranscript = async () => {
  try {
    return await readToggle("voice_transcript");
  } catch (error) {
    logError("Voice transcript setting read failed", error);
    return true;
  }
};

/**
 * Transcribe a voice note. With `echo` and the `voice_transcript` switch on,
 * a "transcribing" reply to the note turns into the quoted transcript;
 * otherwise nothing is sent and only the text comes back.
 */
export const transcribeVoiceNote = async ({
  buffer,
  ctx,
  echo,
  messageId,
}: {
  buffer: Buffer;
  ctx: Context;
  echo: boolean;
  messageId: number;
}) => {
  if (!(echo && (await echoTranscript()))) {
    return await transcribeAudio(buffer, "voice.ogg");
  }
  const status = await ctx.reply(t().voice.transcribing, {
    reply_parameters: { message_id: messageId },
  });
  const text = await transcribeAudio(buffer, "voice.ogg");
  const shown =
    text.length > MAX_TRANSCRIPT_DISPLAY
      ? `${text.slice(0, MAX_TRANSCRIPT_DISPLAY)}...`
      : text;
  const chatId = requireChat(ctx);
  await tg(
    "editMessageText",
    async (api) =>
      await api.editMessageText(
        chatId,
        status.message_id,
        `<blockquote>${escapeHtml(shown)}</blockquote>`,
        { parse_mode: "HTML" }
      ),
    // No retry: the update waits on this call.
    { retry: false }
  );
  return text;
};

/**
 * What the model router reads. The assembled prompt carries the reply quote,
 * the group excerpt and the reminder block; the router wants the sender's own
 * message alone, plus how it arrived — a transcript and a forwarded post read
 * quite differently from something typed.
 */
const routingFor = (
  ctx: BotContext,
  text: string,
  kind: string
): PromptRouting => {
  const replied = ctx.message?.reply_to_message;
  const replyContext = replied?.text ?? replied?.caption;
  const forwarded = ctx.message?.forward_origin !== undefined;
  const routeKind = (() => {
    if (kind === "voice") {
      return "voice_transcript" as const;
    }
    if (forwarded) {
      return "forwarded_content" as const;
    }
    return kind === "photo_caption" || kind === "document_caption"
      ? ("attachment" as const)
      : ("text" as const);
  })();
  return { kind: routeKind, message: text, replyContext };
};

/** What a run reads in place of the words a group file came without. */
const fallbackFor = (files: readonly GroupFile[]) => {
  if (files.length === 0 || files.some((file) => file.kind === "document")) {
    return files.length === 1
      ? "See the attached file."
      : "See the attached files.";
  }
  return files.length === 1
    ? "See the attached photo."
    : "See the attached photos.";
};

/** What the sender reads when the files of their own message did not download. */
const failedTextFor = (files: readonly GroupFile[]) => {
  if (files.some((file) => file.kind === "document")) {
    return t().uploads.fileFailed;
  }
  return files.length > 1 ? t().uploads.photosFailed : t().uploads.photoFailed;
};

/** What a run reads for a replied image it sees inline. */
const INLINE_REPLIED_IMAGE = "[Its image is attached to this message]";

/** What a run reads for a replied file this conversation cannot open. */
const UNOPENABLE_REPLIED_FILE = "[An attachment this conversation cannot open]";

export const registerMessageHandlers = (
  deps: HandlerDeps,
  pipeline: RunPipeline
) => {
  const { bot, botId, ownerId, pendingWork, projectsDir, token } = deps;

  /** The voice note of the message in `ctx`, refused over the upload cap. */
  const downloadVoice = async (ctx: BotContext) => {
    const file = await ctx.getFile();
    assertWithinUploadCap(file.file_size);
    const url = `https://api.telegram.org/file/bot${token}/${file.file_path}`;
    const res = await fetch(url);
    return Buffer.from(await res.arrayBuffer());
  };
  /**
   * A group message's replied photo or document, as the run reads it. The
   * answer is already charged, so a file too large to fetch, or one whose
   * download fails, becomes a note rather than an error. A GIF or a video
   * is never fetched.
   */
  const groupRepliedFile = async (
    ctx: BotContext,
    replied: NonNullable<Message["reply_to_message"]>
  ): Promise<{ image?: RunImage; text?: string }> => {
    const file = groupFileOf(replied);
    if (file === undefined) {
      return {};
    }
    const unopenable = { text: UNOPENABLE_REPLIED_FILE };
    if (!withinDownloadCap(file.fileSize)) {
      return unopenable;
    }
    try {
      if (await canOpenFiles(ctx)) {
        const saved = await saveUploadedFile(deps, { ctx, ...file });
        return { text: describeSavedUpload(saved) };
      }
      const mimeType = inlineTypeOf(file);
      const image =
        mimeType === undefined
          ? undefined
          : await inlineImage(deps, { ctx, ...file, mimeType });
      return image === undefined
        ? unopenable
        : { image, text: INLINE_REPLIED_IMAGE };
    } catch (error) {
      logError("Reply attachment download error", error);
      return unopenable;
    }
  };

  /**
   * The file a message replies to, as the run reads it: saved and described
   * when this conversation can open files. In a group, where the run could
   * otherwise promise to look at it, an image inline when it cannot, and a
   * note that it cannot for anything else.
   */
  const repliedAttachmentOf = async (
    ctx: BotContext
  ): Promise<{ image?: RunImage; text?: string }> => {
    const replied = ctx.message?.reply_to_message;
    if (accessOf(ctx).surface === "group") {
      return replied === undefined ? {} : await groupRepliedFile(ctx, replied);
    }
    const hasFile =
      replied?.photo !== undefined || replied?.document !== undefined;
    const saved = hasFile ? await saveRepliedAttachment(deps, ctx) : undefined;
    return saved === undefined ? {} : { text: describeSavedUpload(saved) };
  };

  /**
   * The request of an answered group upload: its words, then what the run
   * reads for its files and videos, and the photos it sees inline. Undefined
   * once a failed download was told to the sender.
   */
  const uploadRequest = async (
    ctx: BotContext,
    text: string,
    upload: GroupUpload,
    spent: number
  ) => {
    const { files, videos } = upload;
    let request: FilesPrompt | undefined;
    try {
      const attached =
        files.length === 0
          ? { images: [], text: "" }
          : await groupFilesPrompt(deps, ctx, files, spent);
      request = {
        images: attached.images,
        text: [
          text.length > 0 ? text : fallbackFor(files),
          ...(attached.text.length === 0 ? [] : [attached.text]),
          ...(videos === 0 ? [] : [unshownFilesLine([], videos)]),
        ].join("\n\n"),
      };
    } catch (error) {
      logError("Group attachment download error", error);
      await ctx.reply(
        error instanceof UploadTooLargeError
          ? uploadTooLargeText()
          : failedTextFor(files)
      );
    }
    return request;
  };

  /**
   * In a group the bot listens to everything and answers only when addressed;
   * everywhere else every message is a prompt.
   */
  const handleText = async (
    ctx: BotContext,
    text: string,
    messageId: number,
    kind = "text",
    ownWords = text,
    upload?: GroupUpload
  ) => {
    // Claimed before the first await, so a later message never names the
    // topic ahead of this one. A forwarded file with no words names nothing.
    pendingWork
      .track(
        titleImplicitTopic({ content: withoutSavedUploads(ownWords), ctx })
      )
      .catch(logRejection("topic title"));
    const files = upload?.files ?? [];
    const marker =
      upload === undefined ? "" : groupFilesMarker(files, upload.videos);
    if (
      accessOf(ctx).surface === "group" &&
      !(await shouldAnswerInGroup(ctx, {
        botId,
        kind,
        messageId,
        recordText: `${marker} ${text}`.trim(),
        text,
      }))
    ) {
      return;
    }
    let repliedAttachment: string | undefined;
    let request = text;
    const images: RunImage[] = [];
    try {
      const replied = await repliedAttachmentOf(ctx);
      repliedAttachment = replied.text;
      if (replied.image !== undefined) {
        images.push(replied.image);
      }
    } catch (error) {
      logError("Reply attachment download error", error);
      await ctx.reply(
        error instanceof UploadTooLargeError
          ? uploadTooLargeText()
          : t().uploads.repliedFileFailed
      );
      return;
    }
    if (upload !== undefined) {
      const withFiles = await uploadRequest(
        ctx,
        text,
        upload,
        images.reduce((sum, image) => sum + image.data.length, 0)
      );
      if (withFiles === undefined) {
        return;
      }
      request = withFiles.text;
      images.push(...withFiles.images);
    }
    const prompt = buildPromptWithReplyContext(
      ctx,
      request,
      botId,
      repliedAttachment
    );
    const routing: PromptRouting = routingFor(ctx, ownWords, kind);
    if (images.length > 0) {
      routing.images = images;
    }
    const reminderContext = await reminderContextFor(ctx, ownWords);
    const groupChat =
      accessOf(ctx).surface === "group" &&
      ctx.chat !== undefined &&
      ctx.chat.type !== "private"
        ? ctx.chat
        : undefined;
    const requestWithReminderContext =
      reminderContext.length === 0
        ? prompt
        : `${reminderContext}\n\n[Current request]\n${prompt}`;
    const fullPrompt = groupChat
      ? `${await buildGroupMemoryContext(groupChat.id, groupChat.title)}\n\n[Current request]\n${requestWithReminderContext}`
      : requestWithReminderContext;
    await pipeline.handlePrompt(ctx, fullPrompt, routing);
  };

  const forwards = createForwardBursts({
    charge: async (ctx) => await chargePrivateRun(ctx, ownerId),
    pendingWork,
    projectsDir,
    send: async ({ ctx, ownWords, prompt }) => {
      const messageId = ctx.message?.message_id;
      if (messageId !== undefined) {
        await handleText(ctx, prompt, messageId, "forwarded", ownWords);
      }
    },
    token,
    transcribe: async (ctx) =>
      await transcribeVoiceNote({
        buffer: await downloadVoice(ctx),
        ctx,
        echo: true,
        messageId: ctx.message?.message_id ?? 0,
      }),
  });

  // Ahead of every typed handler, uploads included: outside a group a forward
  // of any kind joins its burst, and words typed while one is open join it as
  // the request. A group answers only when addressed, so it goes the usual
  // way. An album forwarded into a draft falls through to the upload handler,
  // which buffers it there (compose took every other draft message already).
  bot.on("message", async (ctx, proceed) => {
    if (accessOf(ctx).surface === "group") {
      await proceed();
      return;
    }
    const { forward_origin: origin, text } = ctx.message;
    if (origin === undefined) {
      if (
        text === undefined ||
        text.startsWith("/") ||
        !forwards.addWords(ctx, text)
      ) {
        await proceed();
      }
      return;
    }
    if (isComposing(await getState(ctx))) {
      await proceed();
      return;
    }
    forwards.add(ctx);
  });

  const repeats = createRepeatGuard();

  /**
   * In a private chat, words that open a new topic and repeat words that
   * opened another one under a minute ago are answered with one line and not
   * run again: a client that sent one message twice opened two topics, and two
   * runs made every write twice. Words sent into a topic the chat had always
   * run and are never compared, so a retry there goes through.
   */
  const skipRepeat = async (ctx: BotContext, text: string) => {
    if (ctx.chat?.type !== "private" || !opensImplicitTopic(ctx)) {
      return false;
    }
    if (!repeats.isRepeat({ chatId: ctx.chat.id, text })) {
      return false;
    }
    leaveImplicitTopic(ctx);
    await ctx.reply(t().repeat.skipped);
    return true;
  };

  bot.on("message:text", async (ctx) => {
    if (await skipRepeat(ctx, ctx.message.text)) {
      return;
    }
    pendingWork
      .track(handleText(ctx, ctx.message.text, ctx.message.message_id))
      .catch(logRejection("handlePrompt"));
  });

  /**
   * A group's photo or document, alone or as a whole album: recorded with its
   * marker, and its files downloaded only once the message is answered.
   */
  const handleGroupUpload = async (ctx: BotContext, upload: GroupUpload) => {
    const { message } = ctx;
    if (message === undefined) {
      return;
    }
    const kind =
      upload.files[0] === undefined
        ? "video_caption"
        : `${upload.files[0].kind}_caption`;
    // A bare video or GIF the run could not see anyway (a reaction to the
    // bot, as often as not) is only recorded.
    if (upload.files.length === 0 && upload.caption.length === 0) {
      await recordInGroup(ctx, {
        kind,
        messageId: message.message_id,
        text: groupFilesMarker([], upload.videos),
      });
      return;
    }
    await handleText(
      ctx,
      upload.caption,
      message.message_id,
      kind,
      upload.caption,
      upload
    );
  };

  const albums = createGroupAlbums({ flush: handleGroupUpload, pendingWork });

  bot.on(
    ["message:photo", "message:document", "message:video", "message:animation"],
    async (ctx, proceed) => {
      if (accessOf(ctx).surface !== "group") {
        await proceed();
        return;
      }
      const file = groupFileOf(ctx.message);
      const albumId = ctx.message.media_group_id;
      if (albumId !== undefined) {
        albums.add(ctx, albumId, file);
        return;
      }
      // A video or a GIF is recorded and its caption answered, but the run
      // never gets the file.
      const caption = ctx.message.caption?.trim() ?? "";
      const upload =
        file === undefined
          ? { caption, files: [], videos: 1 }
          : { caption, files: [file], videos: 0 };
      pendingWork
        .track(handleGroupUpload(ctx, upload))
        .catch(logRejection("handleGroupUpload"));
    }
  );

  bot.on("edited_message:text", (ctx) => {
    if (accessOf(ctx).surface !== "group") {
      return;
    }
    pendingWork
      .track(
        handleText(
          ctx,
          ctx.editedMessage.text,
          ctx.editedMessage.message_id,
          "edited_text"
        )
      )
      .catch(logRejection("handleEditedGroupMessage"));
  });

  bot.on("message:voice", async (ctx) => {
    // Charged before the file is fetched: transcription costs money of its own,
    // so a spent budget must stop the voice note here and not after Groq.
    if (!(await chargePrivateRun(ctx, ownerId))) {
      return;
    }
    const isGroup = accessOf(ctx).surface === "group";
    const state = isGroup ? undefined : await getState(ctx);
    // A sandboxed sender's run works in its own scratch directory, so the
    // project the conversation is pointed at never comes up.
    const { scratch } = runAccessFor(accessOf(ctx));

    if (state !== undefined && !(scratch !== false || state.activeProject)) {
      const { provider } = await routeProvider({
        access: accessOf(ctx),
        state,
      });
      await setRouteProject(state, projectsDir, provider);
    }

    let prompt: string;
    try {
      const buffer = await downloadVoice(ctx);

      prompt = await transcribeVoiceNote({
        buffer,
        ctx,
        echo: !isGroup,
        messageId: ctx.message.message_id,
      });
    } catch (error) {
      logError("Voice transcription error", error);
      if (!isGroup) {
        await ctx.reply(
          error instanceof UploadTooLargeError
            ? uploadTooLargeText()
            : t().voice.failed
        );
      }
      return;
    }

    if (await skipRepeat(ctx, prompt)) {
      return;
    }
    pendingWork
      .track(handleText(ctx, prompt, ctx.message.message_id, "voice"))
      .catch(logRejection("handlePrompt"));
  });
};
